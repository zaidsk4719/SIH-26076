// In-memory + LocalStorage custom locations store
const customLocationsRegistry = new Map<string, IndiaLocation>();

export function registerCustomIndiaLocation(loc: IndiaLocation): void {
  const cleanId = loc.id.toLowerCase().replace(/[^a-z0-9_]/g, '');
  const normalized = { ...loc, id: cleanId };
  customLocationsRegistry.set(cleanId, normalized);
  try {
    if (typeof localStorage !== 'undefined') {
      const existingStr = localStorage.getItem('mausam_custom_locations');
      const existing = existingStr ? JSON.parse(existingStr) : {};
      existing[cleanId] = normalized;
      localStorage.setItem('mausam_custom_locations', JSON.stringify(existing));
    }
  } catch {
    // Ignore storage issues
  }
}

export function getCustomIndiaLocations(): IndiaLocation[] {
  try {
    if (typeof localStorage !== 'undefined') {
      const existingStr = localStorage.getItem('mausam_custom_locations');
      if (existingStr) {
        const existing = JSON.parse(existingStr);
        Object.values(existing).forEach((l: any) => {
          if (l && l.id) {
            customLocationsRegistry.set(l.id.toLowerCase(), l);
          }
        });
      }
    }
  } catch {
    // Ignore
  }
  return Array.from(customLocationsRegistry.values());
}

/**
 * Search locations by query string (matching English/Hindi name or state)
 */
export function searchIndiaLocations(query: string, region: IndiaRegion | 'All' = 'All'): IndiaLocation[] {
  const cleanQ = query.trim().toLowerCase();
  const customLocs = getCustomIndiaLocations();
  const map = new Map<string, IndiaLocation>();
  for (const loc of [...customLocs, ...ALL_INDIA_LOCATIONS]) {
    if (loc && loc.id) {
      map.set(loc.id.toLowerCase(), loc);
    }
  }
  const combined = Array.from(map.values());

  return combined.filter((loc) => {
    const matchesRegion = region === 'All' || loc.region === region;
    if (!matchesRegion) return false;
    if (!cleanQ) return true;

    return (
      loc.name.toLowerCase().includes(cleanQ) ||
      loc.nameHi.toLowerCase().includes(cleanQ) ||
      loc.state.toLowerCase().includes(cleanQ) ||
      loc.stateHi.toLowerCase().includes(cleanQ) ||
      loc.id.toLowerCase().includes(cleanQ) ||
      loc.stationCode.toLowerCase().includes(cleanQ)
    );
  });
}

/**
 * Find exact or best-matching location by ID or Name
 */
export function findIndiaLocation(locIdOrName: string | IndiaLocation | any): IndiaLocation {
  if (!locIdOrName) {
    return ALL_INDIA_LOCATIONS.find((l) => l.id === 'delhi') || ALL_INDIA_LOCATIONS[0];
  }

  if (typeof locIdOrName === 'object') {
    if (locIdOrName.id && locIdOrName.name && locIdOrName.state) {
      return locIdOrName as IndiaLocation;
    }
    locIdOrName = locIdOrName.id || locIdOrName.name || 'delhi';
  }

  const str = String(locIdOrName || 'delhi');
  const clean = str.trim().toLowerCase().replace(/[^a-z0-9]/g, '');

  // Check custom locations first
  const customLocs = getCustomIndiaLocations();
  const customMatch = customLocs.find(
    (l) =>
      l.id.toLowerCase() === str.toLowerCase() ||
      l.id.toLowerCase().replace(/[^a-z0-9]/g, '') === clean ||
      l.name.toLowerCase().replace(/[^a-z0-9]/g, '').includes(clean)
  );
  if (customMatch) return customMatch;

  const exact = ALL_INDIA_LOCATIONS.find(
    (l) => l.id.toLowerCase() === clean || l.name.toLowerCase().replace(/[^a-z0-9]/g, '').includes(clean)
  );
  if (exact) return exact;

  // Partial search in standard list
  const partial = ALL_INDIA_LOCATIONS.find(
    (l) => l.name.toLowerCase().includes(str.toLowerCase()) || l.state.toLowerCase().includes(str.toLowerCase())
  );
  if (partial) return partial;

  // Infer region and climate zone intelligently from input
  const titleName = str.trim();
  const lower = titleName.toLowerCase();

  let region: IndiaRegion = 'Central';
  let climateZone: ClimateZone = 'Deccan';
  let state = 'India';
  let stateHi = 'भारत';
  let elevationMeters = 350;

  // Check state match
  for (const s of INDIA_STATES_AND_UTS) {
    if (lower.includes(s.name.toLowerCase()) || lower.includes(s.nameHi)) {
      state = s.name;
      stateHi = s.nameHi;
      region = s.region;
      climateZone = s.climateZone;
      break;
    }
  }

  // Terrain keywords
  if (lower.includes('himachal') || lower.includes('kashmir') || lower.includes('ladakh') || lower.includes('uttarakhand') || lower.includes('sikkim') || lower.includes('shimla') || lower.includes('manali') || lower.includes('leh')) {
    region = 'North';
    climateZone = 'Himalayan';
    elevationMeters = 1800;
  } else if (lower.includes('rajasthan') || lower.includes('thar') || lower.includes('bikaner') || lower.includes('jaisalmer') || lower.includes('kutch')) {
    region = 'North';
    climateZone = 'Arid';
    elevationMeters = 250;
  } else if (lower.includes('beach') || lower.includes('port') || lower.includes('coastal') || lower.includes('goa') || lower.includes('kerala') || lower.includes('mumbai') || lower.includes('chennai') || lower.includes('puri')) {
    climateZone = 'Coastal';
    elevationMeters = 20;
  } else if (lower.includes('assam') || lower.includes('meghalaya') || lower.includes('shillong') || lower.includes('mizoram') || lower.includes('nagaland')) {
    region = 'North-East';
    climateZone = 'North-East Hills';
    elevationMeters = 1200;
  }

  return {
    id: clean || 'custom_loc',
    name: titleName.includes(',') ? titleName : `${titleName}, ${state}`,
    nameHi: `${titleName}, ${stateHi}`,
    state,
    stateHi,
    region,
    climateZone,
    elevationMeters,
    stationCode: `AWS-${Math.floor(40000 + Math.random() * 9000)}`,
    lat: 28.6139,
    lon: 77.209,
  };
}

function getLocationHash(id: string, name: string): number {
  let hash = 0;
  const str = `${id}:${name}`;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

