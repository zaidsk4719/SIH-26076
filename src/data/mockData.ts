// Dynamic proxy ensuring ANY location across India yields authentic IMD synoptic telemetry
export const MOCK_CURRENT_WEATHER: Record<string, CurrentWeather> = new Proxy(
  BASE_MOCK_CURRENT_WEATHER,
  {
    get(target, prop: string | symbol) {
      if (typeof prop === 'string') {
        const lower = prop.toLowerCase();
        if (lower in target) {
          return target[lower];
        }
        return generateWeatherForLocation(lower);
      }
      return Reflect.get(target, prop);
    },
  }
);

